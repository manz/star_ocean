"""
Saves at the start of SRAM. The game keeps its three 0xA00-byte slots at `$70:6000-7DFF` and the system bytes
(settings, last slot, slot frames) at `$70:7E00-7E6A`: with the Japanese 8 KB SRAM that is file offset 0. The
patch's 32 KB SRAM (scene text, src/dialog/sram_text.s) would put them at 0x6000, so every operand naming that
area moves down by 0x6000 to `$70:0000-1E6A` and an 8 KB `.srm` loads as it is. Sites: the long operands in
banks C0 / C2 / CA, the save code's absolute operands with DB = `$70`, the slot bases of C2:CDBE-D90F
(tests/test_saves.py checks each holds the old address).
"""

.import "core/preamble"

SHIFT := 0x6000

.macro move(site, old) {
    """The address word of the instruction at `site`: `old` - SHIFT."""
    .alloc at site + 1 size 2 {
        .dw old - SHIFT
    }
}

